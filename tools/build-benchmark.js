// Builds site/js/listing-benchmark.js: runs the site's own listing check over the
// Discovery API snapshot and keeps only aggregates (a score histogram and per-dimension
// medians). No listing, seller or per-listing score is written out.
//
//   node tools/build-benchmark.js [path/to/listings_<date>.csv]
const fs = require('fs');
const path = require('path');
const { score, DIMS, W, countGroups } = require('../site/js/listing-check.js');

const SRC = process.argv[2] || 'F:/SaasNova(F)/Claude-Setup/01-Krishna-Personal/02-Side-Business/listing-score-teardown/data/listings_2026-09-24.csv';
const OUT = path.join(__dirname, '../site/js/listing-benchmark.js');
const PER_SELLER = 2;

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h.replace(/^\uFEFF/, ''), r[i]])));
}

const all = parseCsv(fs.readFileSync(SRC, 'utf8'));
const perSeller = new Map();
const rows = all
  .sort((a, b) => a.listing_id.localeCompare(b.listing_id))
  .filter((r) => { const n = perSeller.get(r.seller_id) || 0; perSeller.set(r.seller_id, n + 1); return n < PER_SELLER; });

const results = rows.map((r) => {
  const units = r.pricing_units.split('|').map((s) => s.trim()).filter(Boolean);
  return score({
    title: r.title,
    short: r.short_description,
    highlights: r.highlights.split(' | ').join('\n'),
    long: r.long_description,
    unitNamed: units.some((u) => !/^units?$/i.test(u)) ? 1 : units.length ? 0.34 : 0,
    dimDescribed: r.pricing_dimensions_described_pct === '100' ? 1 : 0, // every dimension described, as the URL lookup judges it
    model: r.pricing_models,
    privateOffer: r.private_offer_request === 'TRUE'
  });
});

const hist = new Array(141).fill(0);
results.forEach((s) => { hist[Math.round(s.raw * 2)]++; });
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); const m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const dimMedian = DIMS.map((_, i) => median(results.map((s) => s.dims[i].score)));
const totals = results.map((s) => s.total);

// Headline stats for the page, on the same capped set the percentile uses.
const text = (r) => [r.title, r.short_description, r.highlights, r.long_description].join('\n');
const share = (fn) => Math.round((rows.filter(fn).length / rows.length) * 100);
const stats = {
  unitsOnly: share((r) => { const u = r.pricing_units.split('|').map((x) => x.trim()).filter(Boolean); return u.length > 0 && u.every((x) => /^units?$/i.test(x)); }),
  noAws: share((r) => countGroups(text(r), W.aws) === 0),
  noSecurity: Math.round((results.filter((x) => x.dims[3].score === 0).length / results.length) * 100),
  mcp: share((r) => /\bMCP\b|Model Context Protocol/i.test(text(r)))
};

const bench = {
  source: 'AWS Marketplace Discovery API, live SaaS listings',
  snapshot: path.basename(SRC).match(/\d{4}-\d{2}-\d{2}/)?.[0] || '',
  harvested: all.length,
  sellers: new Set(all.map((r) => r.seller_id)).size,
  n: rows.length,
  medianTotal: median(totals),
  p90Total: [...totals].sort((a, b) => a - b)[Math.floor(totals.length * 0.9)],
  maxTotal: Math.max(...totals),
  dimMedian,
  stats,
  hist
};
fs.writeFileSync(OUT, `// Generated by tools/build-benchmark.js. Aggregates only; do not edit by hand.\nwindow.LC_BENCH = ${JSON.stringify(bench)};\n`);

const pctOf = (fn) => Math.round((rows.filter(fn).length / rows.length) * 100);
console.log(`harvested ${all.length}, sellers ${bench.sellers}, scored ${rows.length} (max ${PER_SELLER}/seller)`);
console.log('median total', bench.medianTotal, 'p25', totals.sort((a, b) => a - b)[Math.floor(totals.length * 0.25)], 'p75', totals[Math.floor(totals.length * 0.75)], 'p90', totals[Math.floor(totals.length * 0.9)]);
console.log('dim medians', DIMS.map(([, n], i) => `${n} ${dimMedian[i]}`).join(' | '));
console.log('stats', stats);
